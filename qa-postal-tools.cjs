const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const postal = require('./scripts/postal-tools.js');
const total = (kind, service, grams, count = 1) => postal.calculate(kind, service, grams, count).total;

assert.equal(total('letter', 0, 20), 8);
assert.equal(total('plain_letter', 9, 20), 8);
assert.equal(total('express_letter', 0, 20), 15);
assert.equal(total('printed_plain', 0, 20), 6);
assert.equal(total('registered_letter', 0, 20), 28);
assert.equal(total('express_registered_letter', 0, 20), 35);
assert.equal(total('return_letter', 0, 20), 43);
assert.equal(total('registered_packet', 0, 101), 44);
assert.equal(total('letter', 2, 20, 3), 84);
assert.equal(total('book', 0, 2001), 120);
assert.equal(total('packet', 3, 101, 2), 102);
assert.equal(total('postcard', 0, 0), 5);
assert.equal(total('aerogram', 0, 0), 6);
assert.equal(postal.calculate('speedpost', 0, 250, 2, '0', '0').total, 160);
assert.equal(postal.calculate('speedpost', 0, 251, 1, '1', '1').total, 128);
assert.equal(postal.calculate('speedpost', 0, 20000, 1, '2', '0').total, 425);
assert.equal(postal.calculate('parcel', 0, 5000, 1, '0', '0').total, 70);
assert.equal(postal.calculate('parcel', 0, 5001, 2, '1', '1').total, 156);
assert.throws(() => postal.calculate('speedpost', 0, 250, 1), /寄送區域/);
assert.throws(() => total('letter', 0, 0), /重量/);
assert.throws(() => total('letter', 0, 20, 1.5), /正整數/);
assert.throws(() => total('postcard', 2, 0), /寄送方式/);
const root = __dirname;
const files = fs.readdirSync(path.join(root, 'assets/postal/zip-ranges')).filter(name => name.endsWith('.json'));
assert.equal(files.length, 9);
const areas = Object.assign({}, ...files.map(name => JSON.parse(fs.readFileSync(path.join(root, 'assets/postal/zip-ranges', name), 'utf8'))));
assert.equal(Object.keys(areas).length, 371);
assert.ok(areas['106'].length);
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
for (const id of ['postageKind', 'postageService', 'postalZipCity', 'postalZipDistrict', 'postalFullAddress']) assert.ok(html.includes(`id="${id}"`));
console.log('PASS: 郵資計算、欄位與 9 份分區檔內的 371 個六碼區號資料');
